CREATE OR REPLACE FUNCTION public.current_office_role()
RETURNS TEXT
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT profile.role
  FROM public.user_profiles AS profile
  WHERE profile.user_id = auth.uid() AND profile.active AND NOT profile.must_change_password
$$;

CREATE OR REPLACE FUNCTION public.current_office_employee_id()
RETURNS BIGINT
LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT profile.employee_id
  FROM public.user_profiles AS profile
  WHERE profile.user_id = auth.uid() AND profile.role = 'user'
    AND profile.active AND NOT profile.must_change_password
$$;

REVOKE ALL ON FUNCTION public.current_office_role() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.current_office_employee_id() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_office_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.current_office_employee_id() TO authenticated;

-- Permanently remove an employee and their snack history in one transaction.
-- The linked user_profiles row is removed by its employee_id ON DELETE CASCADE;
-- the Supabase Auth account itself is intentionally left untouched.
CREATE OR REPLACE FUNCTION public.delete_employee_permanently(target_employee_id BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  history_rows_deleted BIGINT;
BEGIN
  IF public.current_office_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Admin access required to delete employees.' USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.snack_records AS record
  WHERE record.employee_id = target_employee_id;
  GET DIAGNOSTICS history_rows_deleted = ROW_COUNT;

  DELETE FROM public.employees AS employee
  WHERE employee.id = target_employee_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Employee % not found.', target_employee_id USING ERRCODE = 'P0002';
  END IF;

  RETURN history_rows_deleted;
END;
$$;

REVOKE ALL ON FUNCTION public.delete_employee_permanently(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.delete_employee_permanently(BIGINT) TO authenticated;

-- Permanently remove a snack and its snack history in one transaction.
CREATE OR REPLACE FUNCTION public.delete_snack_permanently(target_snack_id BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  history_rows_deleted BIGINT;
BEGIN
  IF public.current_office_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Admin access required to delete snacks.' USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.snack_records AS record
  WHERE record.snack_id = target_snack_id;
  GET DIAGNOSTICS history_rows_deleted = ROW_COUNT;

  DELETE FROM public.snacks AS snack
  WHERE snack.id = target_snack_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Snack % not found.', target_snack_id USING ERRCODE = 'P0002';
  END IF;

  RETURN history_rows_deleted;
END;
$$;

REVOKE ALL ON FUNCTION public.delete_snack_permanently(BIGINT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.delete_snack_permanently(BIGINT) TO authenticated;

