-- Supabase frontend setup for Office Snacks Tracker.
-- Review your existing public schema before running this file. It never drops or truncates rows.
-- After this file, run database/migrations/2026-11-23-two-role-user-management.sql (two roles + user management).

CREATE TABLE IF NOT EXISTS public.employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_employees_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS public.snacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  unit_price NUMERIC(10,2),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_snacks_name UNIQUE (name),
  CONSTRAINT chk_snacks_unit_price_nonnegative CHECK (unit_price IS NULL OR unit_price >= 0)
);

CREATE TABLE IF NOT EXISTS public.snack_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL,
  snack_id BIGINT NOT NULL,
  quantity INT NOT NULL CHECK (quantity > 0),
  break_type TEXT,
  unit_price NUMERIC(10,2),
  taken_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_record_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE RESTRICT,
  CONSTRAINT fk_record_snack FOREIGN KEY (snack_id) REFERENCES public.snacks(id) ON DELETE RESTRICT,
  CONSTRAINT chk_records_unit_price_nonnegative CHECK (unit_price IS NULL OR unit_price >= 0),
  CONSTRAINT chk_records_break_type CHECK (break_type IS NULL OR break_type IN ('MORNING', 'EVENING'))
);

CREATE TABLE IF NOT EXISTS public.user_profiles (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('admin', 'user')),
  employee_id BIGINT REFERENCES public.employees(id) ON DELETE CASCADE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  password_snapshot TEXT,
  CONSTRAINT chk_user_profile_employee CHECK (
    (role = 'admin' AND employee_id IS NULL) OR (role = 'user' AND employee_id IS NOT NULL)
  )
);

-- Upgrade an existing installation without assigning breaks or prices to old records.
ALTER TABLE public.snacks ADD COLUMN IF NOT EXISTS unit_price NUMERIC(10,2);
ALTER TABLE public.snack_records
  ADD COLUMN IF NOT EXISTS break_type TEXT,
  ADD COLUMN IF NOT EXISTS unit_price NUMERIC(10,2);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_snacks_unit_price_nonnegative' AND conrelid = 'public.snacks'::regclass) THEN
    ALTER TABLE public.snacks ADD CONSTRAINT chk_snacks_unit_price_nonnegative CHECK (unit_price IS NULL OR unit_price >= 0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_records_unit_price_nonnegative' AND conrelid = 'public.snack_records'::regclass) THEN
    ALTER TABLE public.snack_records ADD CONSTRAINT chk_records_unit_price_nonnegative CHECK (unit_price IS NULL OR unit_price >= 0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_records_break_type' AND conrelid = 'public.snack_records'::regclass) THEN
    ALTER TABLE public.snack_records ADD CONSTRAINT chk_records_break_type CHECK (break_type IS NULL OR break_type IN ('MORNING', 'EVENING'));
  END IF;
END $$;

