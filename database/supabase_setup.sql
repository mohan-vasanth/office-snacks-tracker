-- Idempotent sample history for three employees, at most once per IST day.
WITH sample_rows(employee_name, snack_name, quantity) AS (
  VALUES
    ('Supabase Test Employee', 'Supabase Test Tea', 2),
    ('Supabase Test Employee', 'Supabase Test Biscuit', 1),
    ('Supabase Sample Employee 02', 'Supabase Sample Coffee', 3),
    ('Supabase Sample Employee 02', 'Supabase Sample Juice', 1),
    ('Supabase Sample Employee 03', 'Supabase Sample Sandwich', 1),
    ('Supabase Sample Employee 03', 'Supabase Sample Chips', 2)
), today_ist AS (
  SELECT (date_trunc('day', now() AT TIME ZONE 'Asia/Kolkata') AT TIME ZONE 'Asia/Kolkata') AS starts_at
)
INSERT INTO public.snack_records (employee_id, snack_id, quantity, taken_at)
SELECT employee.id, snack.id, sample.quantity, now()
FROM sample_rows AS sample
JOIN public.employees AS employee ON employee.name = sample.employee_name
JOIN public.snacks AS snack ON snack.name = sample.snack_name
CROSS JOIN today_ist
WHERE NOT EXISTS (
  SELECT 1 FROM public.snack_records AS existing
  WHERE existing.employee_id = employee.id
    AND existing.snack_id = snack.id
    AND existing.taken_at >= today_ist.starts_at
    AND existing.taken_at < today_ist.starts_at + INTERVAL '1 day'
);

