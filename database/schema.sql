-- Run this in the Supabase SQL Editor (or another PostgreSQL database).
CREATE TABLE IF NOT EXISTS employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_employees_name UNIQUE (name)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_employees_name_lower ON employees (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_employees_active_name ON employees (active, name);

CREATE TABLE IF NOT EXISTS snacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_snacks_name UNIQUE (name)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_snacks_name_lower ON snacks (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_snacks_active_name ON snacks (active, name);

CREATE TABLE IF NOT EXISTS snack_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL,
  snack_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  taken_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_snack_records_quantity CHECK (quantity > 0),
  CONSTRAINT fk_record_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE RESTRICT,
  CONSTRAINT fk_record_snack FOREIGN KEY (snack_id) REFERENCES snacks(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_records_taken_at ON snack_records (taken_at);
CREATE INDEX IF NOT EXISTS idx_records_employee_time ON snack_records (employee_id, taken_at);
CREATE INDEX IF NOT EXISTS idx_records_snack_time ON snack_records (snack_id, taken_at);
