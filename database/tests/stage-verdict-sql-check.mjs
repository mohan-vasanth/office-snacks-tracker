// LOCAL check (PGlite, NOT Supabase) of the verdict SELECTs used by deploy-two-role.ps1 -Stage check / migrate. Setup: cd database/tests && npm i --no-save @electric-sql/pglite
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
const repo = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const src = readFileSync(repo + 'scripts/deploy-two-role.ps1', 'utf8');
const grab = (re) => { const m = src.match(re); if (!m) throw new Error('SQL not found: ' + re); return m[1]; };
const preSql = grab(/\$pf = Get-CliRow \(& \$ReadRunner @'\r?\n([\s\S]*?)\r?\n'@\)/);
const postSql = grab(/\$pc = Get-CliRow \(& \$ReadRunner @'\r?\n([\s\S]*?)\r?\n'@\)/);
// The ORIGINAL production schema, pinned (commit ed23a6f). Do not use git HEAD: HEAD now contains the two-role setup SQL.
const oldSetup = readFileSync(repo + 'database/tests/fixtures/supabase_setup.pre-two-role.sql', 'utf8');
const migration = readFileSync(repo + 'database/migrations/2026-11-23-two-role-user-management.sql', 'utf8');
const db = new PGlite();
await db.exec(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS; CREATE SCHEMA auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY, email text, encrypted_password text, created_at timestamptz DEFAULT now(), last_sign_in_at timestamptz);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT NULL::uuid $$;`);
await db.exec(oldSetup);
await db.exec(`INSERT INTO auth.users (id,email) VALUES ('00000000-0000-0000-0000-0000000000aa','a@x');
INSERT INTO public.user_profiles (user_id,role,employee_id) VALUES ('00000000-0000-0000-0000-0000000000aa','admin',NULL);`);
let pass = 0, fail = 0; const ok = (n, c, d = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${n}${d ? '  -> ' + d : ''}`); };
const q = async (sql) => (await db.query(sql)).rows[0];
let r = await q(preSql);
ok('pre-flight SELECT is valid SQL and read-only-compatible (starts with select)', /^\s*select/i.test(preSql));
ok('pre-flight on the live-like OLD schema: tables, admin, roles, one-login all true; migration not yet applied', r.tables_exist && r.admin_exists && r.roles_known && r.one_login_per_employee && r.migration_already_applied === false, JSON.stringify(r));
await db.exec(`UPDATE public.user_profiles SET role='manager' WHERE false;`);
await db.exec(migration);
r = await q(postSql);
ok('post-migration SELECT: roles ok, active admin, new functions installed', r.roles_ok && r.active_admin && r.new_functions, JSON.stringify(r));
ok('post-migration SELECT is also a plain read-only SELECT', /^\s*select/i.test(postSql));
await db.exec(`UPDATE public.user_profiles SET active = FALSE WHERE role='admin'`);
r = await q(postSql);
ok('negative: with no ACTIVE admin the post-check verdict is false (script would STOP)', r.active_admin === false, JSON.stringify(r));
r = await q(preSql);
ok('pre-flight after the migration reports migration_already_applied = true', r.migration_already_applied === true);
console.log(`\n${pass} passed, ${fail} failed (local PGlite; NOT Supabase)`); process.exit(fail ? 1 : 0);
