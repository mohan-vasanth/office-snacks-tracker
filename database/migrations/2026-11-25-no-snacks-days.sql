-- Explicit "No Snacks" days for USER accounts. Safe to re-run. Run in the Supabase SQL Editor AFTER
-- 2026-11-23-two-role-user-management.sql.
--   * New table public.no_snack_days: one row per employee per Kolkata day (UNIQUE). It is NOT a snack and never touches
--     public.snacks / public.snack_records, so reports, totals and prices are unaffected.
--   * USER: may insert a row only for their OWN employee; the day is forced to today (Asia/Kolkata) by a trigger; may read only
--     their own rows. ADMIN: may read all rows and delete rows; cannot be blocked by the guards below. No updates for anyone.
--   * Conflict rules (USER only, enforced server-side, race-safe via an advisory lock):
--       - No Snacks cannot be added for a day that already has snack records for that employee.
--       - Snack records cannot be added for a day that already has a No Snacks row.
--   * Direct database connections (auth.uid() IS NULL) and ADMIN snack inserts are not altered. No existing rows are rewritten.
BEGIN;

CREATE TABLE IF NOT EXISTS public.no_snack_days (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES public.employees(id) ON DELETE CASCADE,
  day DATE NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Kolkata')::date),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uk_no_snack_employee_day UNIQUE (employee_id, day)
);
CREATE INDEX IF NOT EXISTS idx_no_snack_days_day ON public.no_snack_days (day);

ALTER TABLE public.no_snack_days ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.no_snack_days FROM anon;
GRANT SELECT, INSERT, DELETE ON public.no_snack_days TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.no_snack_days_id_seq TO authenticated;

DROP POLICY IF EXISTS office_no_snacks_select ON public.no_snack_days;
DROP POLICY IF EXISTS office_no_snacks_insert ON public.no_snack_days;
DROP POLICY IF EXISTS office_no_snacks_delete ON public.no_snack_days;
DROP POLICY IF EXISTS office_no_snacks_select_guard ON public.no_snack_days;
DROP POLICY IF EXISTS office_no_snacks_insert_guard ON public.no_snack_days;
DROP POLICY IF EXISTS office_no_snacks_delete_guard ON public.no_snack_days;
CREATE POLICY office_no_snacks_select ON public.no_snack_days FOR SELECT TO authenticated USING (true);
CREATE POLICY office_no_snacks_select_guard ON public.no_snack_days AS RESTRICTIVE FOR SELECT TO authenticated
  USING (public.current_office_role() = 'admin' OR employee_id = public.current_office_employee_id());
CREATE POLICY office_no_snacks_insert ON public.no_snack_days FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY office_no_snacks_insert_guard ON public.no_snack_days AS RESTRICTIVE FOR INSERT TO authenticated
  WITH CHECK (employee_id = public.current_office_employee_id());
CREATE POLICY office_no_snacks_delete ON public.no_snack_days FOR DELETE TO authenticated USING (true);
CREATE POLICY office_no_snacks_delete_guard ON public.no_snack_days AS RESTRICTIVE FOR DELETE TO authenticated
  USING (public.current_office_role() = 'admin');

-- Trigger 1: a No Snacks row gets the real current day, and is refused if snacks were already recorded that day.
CREATE OR REPLACE FUNCTION public.no_snack_day_insert_guard()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;
  NEW.day := (now() AT TIME ZONE 'Asia/Kolkata')::date;
  NEW.created_at := now();
  PERFORM pg_advisory_xact_lock(hashtextextended('office-no-snacks:' || NEW.employee_id::text || ':' || NEW.day::text, 0));
  IF EXISTS (
    SELECT 1 FROM public.snack_records AS record
    WHERE record.employee_id = NEW.employee_id
      AND (record.taken_at AT TIME ZONE 'Asia/Kolkata')::date = NEW.day
  ) THEN
    RAISE EXCEPTION 'Snacks are already recorded for today, so No Snacks cannot be submitted.' USING ERRCODE = '23505';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.no_snack_day_insert_guard() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_no_snack_day_insert_guard ON public.no_snack_days;
CREATE TRIGGER trg_no_snack_day_insert_guard BEFORE INSERT ON public.no_snack_days
  FOR EACH ROW EXECUTE FUNCTION public.no_snack_day_insert_guard();

-- Trigger 2: a USER cannot add snack records for a day on which they already submitted No Snacks.
CREATE OR REPLACE FUNCTION public.snack_record_no_snacks_guard()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  today DATE := (now() AT TIME ZONE 'Asia/Kolkata')::date;
BEGIN
  IF auth.uid() IS NULL OR public.current_office_role() = 'admin' THEN
    RETURN NEW;
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('office-no-snacks:' || NEW.employee_id::text || ':' || today::text, 0));
  IF EXISTS (SELECT 1 FROM public.no_snack_days AS d WHERE d.employee_id = NEW.employee_id AND d.day = today) THEN
    RAISE EXCEPTION 'No Snacks was already submitted for today, so snacks cannot be added.' USING ERRCODE = '23505';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.snack_record_no_snacks_guard() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_snack_record_no_snacks_guard ON public.snack_records;
CREATE TRIGGER trg_snack_record_no_snacks_guard BEFORE INSERT ON public.snack_records
  FOR EACH ROW EXECUTE FUNCTION public.snack_record_no_snacks_guard();

NOTIFY pgrst, 'reload schema';
COMMIT;
